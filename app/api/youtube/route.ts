import { getSession } from "@/lib/auth";
import { fail, unauthorized } from "@/lib/api";
import {
  fetchTranscript,
  transcriptToSource,
  TranscriptError,
} from "@/lib/youtube";
import { parseYouTubeId } from "@/lib/youtube-url";

// Fetching a watch page and its captions is two round trips to YouTube.
export const maxDuration = 60;

/**
 * Turns a YouTube link into a source the rest of the app can use.
 *
 * Returns the text rather than storing it, so the same endpoint serves both
 * building a new kit and adding a video to one that exists — the caller
 * decides what to do with it.
 */
export async function POST(request: Request) {
  const session = await getSession();
  if (!session) return unauthorized();

  const { url } = (await request.json().catch(() => ({}))) as {
    url?: string;
  };

  if (!url?.trim()) return fail("Paste a YouTube link first.");

  const videoId = parseYouTubeId(url);
  if (!videoId) {
    return fail(
      "That does not look like a YouTube link.",
      400,
      "A link like youtube.com/watch?v=… or youtu.be/… is what this expects.",
    );
  }

  try {
    const transcript = await fetchTranscript(videoId);
    const source = transcriptToSource(transcript);

    return Response.json({
      ...source,
      videoId,
      author: transcript.author,
      autoGenerated: transcript.autoGenerated,
      chars: source.content.length,
    });
  } catch (cause) {
    if (cause instanceof TranscriptError) {
      return fail(cause.message, 422, cause.hint);
    }
    return fail(
      "Something went wrong reading that video.",
      500,
      cause instanceof Error ? cause.message : undefined,
    );
  }
}
